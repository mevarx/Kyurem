# Kyurem M4 load benchmark — PowerShell 7 twin of bench-load.sh.
#
# Boots a real gateway process with one real demo agent (go-echo) behind it,
# drives closed-loop A2A traffic through the proxy with kyurem-loadgen and
# prints one Markdown row per tier. The gateway's admin /metrics snapshots
# around each tier supply goroutine/RSS deltas.
#
# Tiers default to 1k, 5k, 10k concurrent streams. Each tier runs for a
# fixed duration with one request in flight per worker, so "1k streams"
# means 1,000 simultaneously open A2A exchanges, not 1,000 total requests.
#
#   pwsh demo/scenarios/bench-load.ps1
#   $env:KYUREM_BENCH_TIERS = '100'; pwsh demo/scenarios/bench-load.ps1
#   $env:KYUREM_BENCH_MODE  = 'send'; pwsh demo/scenarios/bench-load.ps1
#   $env:KYUREM_BENCH_OUT   = 'C:\temp\bench'; pwsh demo/scenarios/bench-load.ps1
#
# Raw per-tier JSON lands in $env:KYUREM_BENCH_OUT (default
# demo/bin/bench-results); it is the published raw data behind
# docs/benchmarks.md. Requirements: PowerShell 7, go. No Docker.
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$Root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSCommandPath))
Set-Location $Root

$Tiers = if ($env:KYUREM_BENCH_TIERS) { $env:KYUREM_BENCH_TIERS } else { '1k,5k,10k' }
$Mode = if ($env:KYUREM_BENCH_MODE) { $env:KYUREM_BENCH_MODE } else { 'stream' }
$OutDir = if ($env:KYUREM_BENCH_OUT) { $env:KYUREM_BENCH_OUT } else { 'demo/bin/bench-results' }
$Bin = 'demo/bin'

# Concurrent streams and the run shape per tier. The ramp staggers worker
# starts so a listener accept queue never sees a SYN burst; the duration
# leaves a steady-state window after the ramp completes.
$TierStreams = @{ '100' = 100; '1k' = 1000; '5k' = 5000; '10k' = 10000 }
$TierShape = @{
    '100' = @{ Duration = '5s'; Ramp = '200ms' }
    '1k'  = @{ Duration = '20s'; Ramp = '2s' }
    '5k'  = @{ Duration = '30s'; Ramp = '5s' }
    '10k' = @{ Duration = '30s'; Ramp = '10s' }
}

$Jobs = @()
function Fail($msg) { Write-Host "FAIL: $msg" -ForegroundColor Red; exit 1 }
function Note($msg) { Write-Host "== $msg" }

function Wait-Http($url, $name) {
    for ($i = 0; $i -lt 150; $i++) {
        try {
            $r = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 2
            if ($r.StatusCode -eq 200) { return }
        } catch { Start-Sleep -Milliseconds 200 }
    }
    Fail "$name not ready: $url"
}

# Start-Background launches a process without a console window. The
# -WindowStyle parameter only exists on Windows, so it is added there only:
# the script also runs on Linux CI.
function Start-Background($file, $arguments, $stdout, $stderr) {
    $params = @{
        FilePath               = $file
        ArgumentList           = $arguments
        PassThru               = $true
        RedirectStandardOutput = $stdout
        RedirectStandardError  = $stderr
    }
    if ($IsWindows) { $params.WindowStyle = 'Hidden' }
    Start-Process @params
}

New-Item -ItemType Directory -Force -Path $OutDir, $Bin | Out-Null

$tierNames = @($Tiers -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
if ($tierNames.Count -eq 0) { Fail 'no tiers selected' }
$maxStreams = 0
foreach ($tier in $tierNames) {
    if (-not $TierStreams.ContainsKey($tier)) {
        Fail "unknown tier '$tier' (want 100, 1k, 5k or 10k)"
    }
    $maxStreams = [Math]::Max($maxStreams, $TierStreams[$tier])
}
# Headroom over the concurrency the loadgen will open: the cap is a
# production guard, not the thing under test.
$streamCap = $maxStreams + [int]($maxStreams / 10) + 64

try {
    Note 'building binaries'
    go build -o "$Bin/kyurem.exe" ./gateway/cmd/kyurem
    if ($LASTEXITCODE -ne 0) { Fail 'build gateway' }
    go build -o "$Bin/go-echo.exe" ./demo/agents/go-echo
    if ($LASTEXITCODE -ne 0) { Fail 'build go-echo' }
    go build -o "$Bin/kyurem-loadgen.exe" ./gateway/test/bench/loadgen
    if ($LASTEXITCODE -ne 0) { Fail 'build kyurem-loadgen' }

    Note 'allocating loopback ports'
    $ports = @(& "$Bin/kyurem-loadgen.exe" --allocate-ports 4)
    if ($LASTEXITCODE -ne 0 -or $ports.Count -ne 4) { Fail 'could not allocate four loopback ports' }
    $A2APort, $AdminPort, $MgmtPort, $EchoPort = $ports | ForEach-Object { [int]$_ }

    $cfg = Join-Path $OutDir 'bench-config.yaml'
    @"
# Generated by demo/scenarios/bench-load.ps1 — free ports, one agent, a
# stream cap above the tier size. Do not edit; regenerate with the script.
listeners:
  a2a:
    addr: "127.0.0.1:$A2APort"
  admin:
    addr: "127.0.0.1:$AdminPort"
  mgmt:
    addr: "127.0.0.1:$MgmtPort"
logging:
  level: warn
  format: text
telemetry:
  otlp_endpoint: ""
management:
  enabled: true
  storage:
    driver: memory
    memory_capacity: 4096
agents:
  - name: echo
    upstreams:
      - url: "http://127.0.0.1:$EchoPort"
        binding: JSONRPC
card_cache:
  ttl: 60s
  stale_grace: 10m
limits:
  max_concurrent_streams: $streamCap
  max_request_body_bytes: 67108864
  shutdown_grace: 5s
  timeouts:
    connect: 5s
    response_header: 30s
    request: 0s
"@ | Set-Content -Path $cfg -Encoding utf8

    & "$Bin/kyurem.exe" validate --config $cfg | Out-Null
    if ($LASTEXITCODE -ne 0) { Fail 'generated bench config does not validate' }

    Note "booting go-echo (:$EchoPort) and the gateway (:$A2APort, admin :$AdminPort)"
    $Jobs += Start-Background "$Bin/go-echo.exe" "--port $EchoPort" `
        (Join-Path $OutDir 'go-echo.log') (Join-Path $OutDir 'go-echo.err.log')
    $Jobs += Start-Background "$Bin/kyurem.exe" "serve --config $cfg" `
        (Join-Path $OutDir 'gateway.log') (Join-Path $OutDir 'gateway.err.log')

    Wait-Http "http://127.0.0.1:$AdminPort/healthz" 'gateway admin'
    Wait-Http "http://127.0.0.1:$AdminPort/readyz" 'gateway readiness'
    # Fetch the card THROUGH the gateway once: discovery + cache warm-up
    # happen before the first timed tier, exactly as a real client would.
    Wait-Http "http://127.0.0.1:$A2APort/a2a/echo/.well-known/agent-card.json" 'agent card via gateway'

    Write-Host '| tier | mode | streams | completed | failed | p50 ms | p95 ms | p99 ms | req/s | goroutines Δ | RSS Δ MiB |'
    Write-Host '|---|---|---|---|---|---|---|---|---|---|---|'

    foreach ($tier in $tierNames) {
        $streams = $TierStreams[$tier]
        $shape = $TierShape[$tier]
        $label = "$tier-$Mode"
        $jsonPath = Join-Path $OutDir "$label.json"

        Note "$label`: $streams concurrent, duration $($shape.Duration), ramp $($shape.Ramp)"
        $loadArgs = @(
            '--gateway-url', "http://127.0.0.1:$A2APort/a2a/echo",
            '--admin-url', "http://127.0.0.1:$AdminPort",
            '--mode', $Mode,
            '--streams', "$streams",
            '--duration', $shape.Duration,
            '--ramp', $shape.Ramp,
            '--label', $label,
            '--output', 'json'
        )
        $raw = & "$Bin/kyurem-loadgen.exe" @loadArgs
        if ($LASTEXITCODE -ne 0) { Fail "tier $label failed; raw output kept at $jsonPath" }
        $raw | Set-Content -Path $jsonPath -Encoding utf8
        $r = $raw | ConvertFrom-Json

        $goroutines = [int]$r.gateway.after.go_goroutines - [int]$r.gateway.before.go_goroutines
        $rss = ([double]$r.gateway.after.resident_memory_bytes -
            [double]$r.gateway.before.resident_memory_bytes) / 1MB
        Write-Host ("| {0} | {1} | {2} | {3} | {4} | {5:F1} | {6:F1} | {7:F1} | {8:F0} | {9:+0;-0;0} | {10:+0.0;-0.0;0.0} |" -f `
                $r.label, $r.mode, $r.streams, $r.completed, $r.failed,
            $r.latency.p50_ms, $r.latency.p95_ms, $r.latency.p99_ms,
            $r.throughput_rps, $goroutines, $rss)
    }

    Write-Host ''
    Note "raw results: $OutDir"
    Note 'paste the tables (and the machine/Go versions above) into docs/benchmarks.md'
} finally {
    foreach ($job in $Jobs) {
        if ($job -and -not $job.HasExited) {
            Stop-Process -Id $job.Id -Force -ErrorAction SilentlyContinue
        }
    }
}
