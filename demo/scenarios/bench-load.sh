#!/usr/bin/env bash
# Kyurem M4 load benchmark — bash driver (Linux/macOS/Git Bash).
#
# Boots a real gateway process with one real demo agent (go-echo) behind it,
# then drives closed-loop A2A traffic through the proxy with kyurem-loadgen
# and prints one Markdown row per tier. The gateway's admin /metrics snapshot
# around each tier supplies goroutine/RSS/CPU deltas.
#
# Tiers default to 1k, 5k, 10k concurrent streams. Each tier runs for a
# fixed duration with one request in flight per worker, so "1k streams"
# means 1,000 simultaneously open A2A exchanges, not 1,000 total requests.
#
#   ./demo/scenarios/bench-load.sh
#   KYUREM_BENCH_TIERS=100 ./demo/scenarios/bench-load.sh      # quick smoke
#   KYUREM_BENCH_MODE=send ./demo/scenarios/bench-load.sh       # no SSE
#   KYUREM_BENCH_OUT=/tmp/bench ./demo/scenarios/bench-load.sh  # results dir
#
# Holding streams open (the "10k concurrent" test; see docs/benchmarks.md):
#   KYUREM_BENCH_HOLD=1 KYUREM_BENCH_SYNTHETIC=1 KYUREM_BENCH_WORDS=20 \
#   KYUREM_BENCH_CHUNK_DELAY=3s KYUREM_BENCH_TIMEOUT=120s \
#   KYUREM_BENCH_DURATION=150s KYUREM_BENCH_SETTLE=15 \
#   KYUREM_BENCH_TIERS=1k,2k,5k,7.5k,10k ./demo/scenarios/bench-load.sh
# Other knobs: KYUREM_BENCH_RAMP, KYUREM_BENCH_LOG_LEVEL, KYUREM_PPROF=1
# (gateway /debug/pprof on the admin port), ECHO_PPROF=addr (agent pprof).
#
# Raw per-tier JSON lands in $KYUREM_BENCH_OUT (default
# demo/bin/bench-results); it is the published raw data behind
# docs/benchmarks.md. Requires: bash, go, curl. No Docker.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

TIERS="${KYUREM_BENCH_TIERS:-1k,5k,10k}"
MODE="${KYUREM_BENCH_MODE:-stream}"
OUT="${KYUREM_BENCH_OUT:-demo/bin/bench-results}"
# Stream shape: words * chunk delay is roughly how long each stream stays
# open. Defaults keep the historical short stream; raise both to hold
# streams concurrently rather than churning through them.
CHUNK_DELAY="${KYUREM_BENCH_CHUNK_DELAY:-40ms}"
WORDS="${KYUREM_BENCH_WORDS:-3}"
# KYUREM_BENCH_SYNTHETIC=1 swaps the SDK-backed echo stream for a minimal SSE
# writer so the gateway, not the demo agent, is what the tier measures.
SYNTHETIC="${KYUREM_BENCH_SYNTHETIC:-}"
# KYUREM_BENCH_HOLD=1: every worker opens exactly one stream, so the run ends
# when all streams finish and the gateway must have peaked at the full tier.
HOLD_ARGS=()
HOLD="${KYUREM_BENCH_HOLD:-}"
# Seconds to idle after each tier before sampling gateway recovery (0 = skip).
SETTLE="${KYUREM_BENCH_SETTLE:-0}"
# Per-request deadline; must exceed the stream length (words * chunk delay).
TIMEOUT="${KYUREM_BENCH_TIMEOUT:-60s}"
MESSAGE="w"
for ((i = 1; i < WORDS; i++)); do MESSAGE+=" w"; done
BIN="demo/bin"

EXE=""
case "$(uname -s)" in
    MINGW* | MSYS* | CYGWIN*) EXE=".exe" ;;
esac

fail() {
    echo "FAIL: $*" >&2
    exit 1
}

note() { echo "== $*"; }

# tier_streams prints the tier's concurrent-stream count (accepts 1k/1000).
tier_streams() {
    case "$1" in
        100) echo 100 ;;
        1k | 1000) echo 1000 ;;
        2k) echo 2000 ;;
        5k) echo 5000 ;;
        7.5k | 7500) echo 7500 ;;
        10k) echo 10000 ;;
        *) fail "unknown tier '$1' (want 100, 1k, 2k, 5k, 7.5k or 10k)" ;;
    esac
}

# tier_shape prints "<duration> <ramp>" for a tier. The ramp staggers worker
# starts so a Windows/Go listener accept queue never sees a SYN burst; the
# duration leaves a steady-state window after the ramp completes.
tier_shape() {
    case "$1" in
        100) echo "5s 200ms" ;;
        1k) echo "20s 2s" ;;
        2k) echo "20s 3s" ;;
        5k) echo "30s 5s" ;;
        7.5k | 7500) echo "30s 8s" ;;
        10k) echo "30s 10s" ;;
    esac
}

# Detect a Python interpreter for the small JSON->Markdown renderer.
PYTHON=""
for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1; then
        PYTHON="$candidate"
        break
    fi
done
[[ -n "$PYTHON" ]] || fail "python (or python3) is required to render the results table"

mkdir -p "$OUT" "$BIN"

# ---------------------------------------------------------------- build ----
note "building binaries"
go build -o "$BIN/kyurem$EXE" ./gateway/cmd/kyurem
go build -o "$BIN/go-echo$EXE" ./demo/agents/go-echo
go build -o "$BIN/kyurem-loadgen$EXE" ./gateway/test/bench/loadgen

# ---------------------------------------------------------------- ports ----
mapfile -t PORTS < <("$BIN/kyurem-loadgen$EXE" --allocate-ports 4)
[[ ${#PORTS[@]} -eq 4 ]] || fail "could not allocate four loopback ports"
A2A_PORT="${PORTS[0]}"
ADMIN_PORT="${PORTS[1]}"
MGMT_PORT="${PORTS[2]}"
ECHO_PORT="${PORTS[3]}"

MAX_STREAMS=0
for tier in ${TIERS//,/ }; do
    streams="$(tier_streams "$tier")"
    ((streams > MAX_STREAMS)) && MAX_STREAMS="$streams"
done
# Headroom over the concurrency the loadgen will open: the cap is a
# production guard, not the thing under test.
STREAM_CAP=$((MAX_STREAMS + MAX_STREAMS / 10 + 64))

CFG="$OUT/bench-config.yaml"
cat >"$CFG" <<EOF
# Generated by demo/scenarios/bench-load.sh — free ports, one agent, a
# stream cap above the tier size. Do not edit; regenerate with the script.
listeners:
  a2a:
    addr: "127.0.0.1:$A2A_PORT"
  admin:
    addr: "127.0.0.1:$ADMIN_PORT"
  mgmt:
    addr: "127.0.0.1:$MGMT_PORT"
logging:
  level: ${KYUREM_BENCH_LOG_LEVEL:-warn}
  format: text
telemetry:
  otlp_endpoint: ""
management:
  enabled: true
  storage:
    driver: memory
    memory_capacity: 4096
agents:
  - name: echo
    upstreams:
      - url: "http://127.0.0.1:$ECHO_PORT"
        binding: JSONRPC
card_cache:
  ttl: 60s
  stale_grace: 10m
limits:
  max_concurrent_streams: $STREAM_CAP
  max_request_body_bytes: 67108864
  shutdown_grace: 5s
  timeouts:
    connect: 5s
    response_header: 30s
    request: 0s
EOF

"$BIN/kyurem$EXE" validate --config "$CFG" >/dev/null || fail "generated bench config does not validate"

# ---------------------------------------------------------------- boot -----
GW_PID=""
ECHO_PID=""
cleanup() {
    set +e
    [[ -n "$GW_PID" ]] && kill "$GW_PID" 2>/dev/null
    [[ -n "$ECHO_PID" ]] && kill "$ECHO_PID" 2>/dev/null
    [[ -n "$GW_PID" ]] && wait "$GW_PID" 2>/dev/null
    [[ -n "$ECHO_PID" ]] && wait "$ECHO_PID" 2>/dev/null
}
trap cleanup EXIT INT TERM

wait_http() {
    local url="$1" name="$2"
    for _ in $(seq 1 150); do
        if curl -sf -o /dev/null --max-time 2 "$url"; then
            return 0
        fi
        sleep 0.2
    done
    fail "$name not ready: $url"
}

note "booting go-echo (:$ECHO_PORT) and the gateway (:$A2A_PORT, admin :$ADMIN_PORT)"
"$BIN/go-echo$EXE" --port "$ECHO_PORT" --chunk-delay "$CHUNK_DELAY" ${SYNTHETIC:+--synthetic-stream} ${ECHO_PPROF:+--pprof-addr "$ECHO_PPROF"} >"$OUT/go-echo.log" 2>&1 &
ECHO_PID=$!
"$BIN/kyurem$EXE" serve --config "$CFG" >"$OUT/gateway.log" 2>&1 &
GW_PID=$!

wait_http "http://127.0.0.1:$ADMIN_PORT/healthz" "gateway admin"
wait_http "http://127.0.0.1:$ADMIN_PORT/readyz" "gateway readiness"
# Fetch the card THROUGH the gateway once: discovery + cache warm-up happen
# before the first timed tier, exactly as a real client would find the agent.
wait_http "http://127.0.0.1:$A2A_PORT/a2a/echo/.well-known/agent-card.json" "agent card via gateway"

# ---------------------------------------------------------------- tiers ----
HEADER="| tier | mode | streams | completed | failed | p50 ms | p95 ms | p99 ms | req/s | peak active | drain s | gw CPU s | goroutines Δ | RSS Δ MiB |"
SEP="|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"
echo "$HEADER"
echo "$SEP"

for tier in ${TIERS//,/ }; do
    streams="$(tier_streams "$tier")"
    read -r duration ramp <<<"$(tier_shape "$tier")"
    duration="${KYUREM_BENCH_DURATION:-$duration}"
    ramp="${KYUREM_BENCH_RAMP:-$ramp}"
    HOLD_ARGS=()
    if [[ -n "$HOLD" ]]; then
        HOLD_ARGS=(--requests "$streams" --require-peak)
        # Open at most ~330 new streams/s: faster ramps overran the 5s upstream
        # dial timeout on this 2-vCPU host (see docs/benchmarks.md).
        [[ -z "${KYUREM_BENCH_RAMP:-}" ]] && ramp="$(((streams + 329) / 330))s"
    fi
    label="$tier-$MODE"
    json="$OUT/$label.json"

    note "$label: $streams concurrent, duration $duration, ramp $ramp"
    if ! "$BIN/kyurem-loadgen$EXE" \
        --gateway-url "http://127.0.0.1:$A2A_PORT/a2a/echo" \
        --admin-url "http://127.0.0.1:$ADMIN_PORT" \
        --mode "$MODE" \
        --streams "$streams" \
        --duration "$duration" \
        --ramp "$ramp" \
        --label "$label" \
        --timeout "$TIMEOUT" \
        ${HOLD_ARGS[@]+"${HOLD_ARGS[@]}"} \
        --message "$MESSAGE" \
        --output json >"$json"; then
        fail "tier $label failed; raw output kept at $json"
    fi

    "$PYTHON" - "$json" <<'PY'
import json
import sys

with open(sys.argv[1], encoding="utf-8") as fh:
    r = json.load(fh)
g = r.get("gateway") or {}
before = g.get("before") or {}
after = g.get("after") or {}
lat = r.get("latency") or {}
goroutines = after.get("go_goroutines", 0) - before.get("go_goroutines", 0)
rss = (after.get("resident_memory_bytes", 0) - before.get("resident_memory_bytes", 0)) / (1024 * 1024)
print(
    "| {label} | {mode} | {streams} | {completed} | {failed} | {p50:.1f} | {p95:.1f} | "
    "{p99:.1f} | {rps:.0f} | {peak:.0f} | {drain:.1f} | {cpu:.1f} | {goroutines:+d} | {rss:+.1f} |".format(
        peak=g.get("active_streams_peak", 0),
        drain=g.get("drain_seconds", 0),
        cpu=after.get("cpu_seconds_total", 0) - before.get("cpu_seconds_total", 0),
        p50=lat.get("p50_ms", 0),
        p95=lat.get("p95_ms", 0),
        p99=lat.get("p99_ms", 0),
        rps=r.get("throughput_rps", 0),
        goroutines=goroutines,
        rss=rss,
        **r,
    )
)
PY

    # Recovery check: with the load gone, goroutines, memory and the active
    # gauge should settle back near the pre-run baseline.
    if ((SETTLE > 0)); then
        sleep "$SETTLE"
        note "$label settled after ${SETTLE}s idle: $(curl -fsS "http://127.0.0.1:$ADMIN_PORT/metrics" |
            awk '/^go_goroutines /{g=$2} /^process_resident_memory_bytes /{r=$2} /^go_memstats_heap_inuse_bytes /{h=$2} /^kyurem_proxy_active_streams[{ ]/{a+=$2} END{printf "goroutines=%d rss_mib=%.0f heap_inuse_mib=%.0f active_streams=%d", g, r/1048576, h/1048576, a}')"
    fi
done

echo
note "raw results: $OUT"
note "paste the tables (and the machine/Go versions above) into docs/benchmarks.md"
